"""Build docs/profile_comparison.md: the same request ranked for every traveller profile.

    python scripts/compare_profiles.py

The file is generated (no hand editing, no timestamps), so the numbers in the report can
be reproduced exactly. A test checks that the committed file matches this script.
"""
import sys
from datetime import date, time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))   # so it runs as a plain script

from busbidder.comparison import winner_rank_matrix
from busbidder.explain import explain_top_offer, format_minutes
from busbidder.filtering import hard_constraint_lines
from busbidder.loader import (load_companies, load_destinations, load_offers, load_profiles,
                              load_scoring_config)
from busbidder.marketplace import Marketplace
from busbidder.models import TravelRequest
from busbidder.scoring_config import set_config

# The example request from the spec (Madrid to Malaga, 12-14 July, EUR 50, morning, max 1 transfer,
# changeable ticket required). It is IDENTICAL for every profile.
SPEC_REQUEST = dict(destination="Malaga", date_from=date(2026, 7, 12), date_to=date(2026, 7, 14),
                    max_budget=50.0, max_transfers=1, require_changeable=True,
                    preferred_departure=time(9, 0))

DESCRIPTIONS = {
    "budget_traveller": "Wants the lowest price and accepts a slower journey.",
    "business_traveller": "Needs a fast journey that leaves at a convenient time.",
    "flexible_tourist": "Plans may change, so a changeable and refundable ticket matters most.",
    "environment_focused": "Chooses on low emissions and few transfers.",
}
# Second experiment: each traveller also has a preferred departure time of their own.
OWN_PREFERRED = {"budget_traveller": time(9, 0), "business_traveller": time(8, 0),
                 "flexible_tourist": time(10, 0), "environment_focused": time(9, 0)}


def _table(headers: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def _marketplace() -> Marketplace:
    set_config(load_scoring_config())
    companies, destinations = load_companies(), load_destinations()
    offers = load_offers("data/offers.csv", [d.name for d in destinations],
                         [c.name for c in companies]).offers
    return Marketplace(companies, destinations, offers, load_profiles())


def build_report() -> str:
    m = _marketplace()
    request = TravelRequest(**SPEC_REQUEST, profile="(compare)")
    filtered, rankings = m.compare_profiles(request)
    names = list(rankings)
    out = ["# Traveller profile comparison", "",
           "Generated by `python scripts/compare_profiles.py`. Do not edit by hand: a test checks that this file "
           "matches the script, so every number here can be reproduced.", "",
           "## The request", "",
           f"Madrid to {request.destination}, departing {request.date_from} to {request.date_to}, "
           f"preferred departure {request.preferred_departure:%H:%M} (soft). The request is **identical** for "
           "every profile, so only the weights differ.", "",
           "Hard constraints (breaking one removes the offer before ranking):", ""]
    out += [f"- {line}" for line in hard_constraint_lines(request)]
    out += ["", f"Of {filtered.considered} offers, {len(filtered.kept)} remain after filtering. "
            "These same offers are ranked for every profile.", "",
            "## The profiles", ""]
    weight_cols = [c for c in ("price", "duration", "departure", "flexibility", "transfers", "emissions")
                   if any(c in m.profiles[n] for n in names)]
    rows = [[n, DESCRIPTIONS.get(n, "")] + [f"{m.profiles[n].get(c, 0) * 100:.0f}%" for c in weight_cols]
            for n in names]
    out += [_table(["Profile", "Traveller"] + weight_cols, rows), "",
            "## Result: the same offers, different recommendations", ""]
    rows = []
    for n in names:
        top, second = rankings[n][0], rankings[n][1]
        o = top.offer
        rows.append([n, f"{o.offer_id}", o.company, f"{o.travel_date:%d %b} {o.departure_time:%H:%M}",
                     f"{o.price:.2f}", format_minutes(o.duration_minutes), str(o.transfers),
                     o.fare.fare_type, f"{top.total_score:.1f}",
                     f"{second.offer.offer_id} ({second.total_score:.1f})"])
    out += [_table(["Profile", "Winner", "Company", "Departs", "EUR", "Duration", "Transfers", "Fare",
                    "Total", "Runner-up"], rows), ""]

    matrix = winner_rank_matrix(rankings)
    out += ["### How each winner ranks under the other profiles", "",
            "Rank 1 is the recommendation. A winner that is far down under another profile shows "
            "how much the weights matter.", ""]
    rows = [[f"{w.offer.offer_id} ({w.offer.company})"] + [str(r[n]) for n in names] for w, r in matrix]
    out += [_table(["Winner of"] + names, rows), ""]
    off_diagonal = [(r[n], w.offer.offer_id, n) for w, r in matrix for n in names
                    if rankings[n][0].offer.offer_id != w.offer.offer_id]
    worst = max(off_diagonal) if off_diagonal else None
    out += [f"- {len(matrix)} different offers win, from {len({w.offer.company for w, _ in matrix})} "
            f"different companies ({', '.join(sorted({w.offer.company for w, _ in matrix}))})."]
    if worst:
        out += [f"- Largest disagreement: {worst[1]} is the recommendation for one profile but only rank "
                f"{worst[0]} of {len(filtered.kept)} for `{worst[2]}`."]
    out += [""]

    out += ["## Top three and explanation per profile", ""]
    for n in names:
        weights = m.profiles[n]
        cols = [c for c in weight_cols if c in weights]
        req = TravelRequest(**SPEC_REQUEST, profile=n)
        out += [f"### {n}", "", DESCRIPTIONS.get(n, ""), ""]
        rows = []
        for r in rankings[n][:3]:
            o = r.offer
            rows.append([str(r.rank), o.offer_id, o.company, f"{o.travel_date:%d %b} {o.departure_time:%H:%M}",
                         f"{o.price:.2f}", format_minutes(o.duration_minutes), str(o.transfers), o.fare.fare_type]
                        + [f"{r.criterion_scores[c]:.1f}" for c in cols] + [f"{r.total_score:.1f}"])
        out += [_table(["#", "Offer", "Company", "Departs", "EUR", "Duration", "Tr", "Fare"] + cols + ["Total"], rows), "",
                "Explanation generated for the top offer:", ""]
        out += [f"> {line}" for line in explain_top_offer(rankings[n], req, weights).text().splitlines()]
        out += [""]

    out += ["## Variation: each traveller has their own preferred departure time", "",
            "Same request and weights, but the preferred departure differs per traveller (a business traveller "
            "wants an early bus, a tourist a later one). Only the soft `departure` score changes.", ""]
    rows = []
    for n in names:
        req = TravelRequest(**{**SPEC_REQUEST, "preferred_departure": OWN_PREFERRED[n]}, profile=n)
        _, ranked = m.search(req)
        top = ranked[0]
        o = top.offer
        rows.append([n, f"{OWN_PREFERRED[n]:%H:%M}", o.offer_id, o.company,
                     f"{o.travel_date:%d %b} {o.departure_time:%H:%M}", f"{top.total_score:.1f}",
                     "same as above" if o.offer_id == rankings[n][0].offer.offer_id else "changed"])
    out += [_table(["Profile", "Preferred", "Winner", "Company", "Departs", "Total", "vs. table above"], rows), "",
            "## How to read this", "",
            "- The ranking is a recommendation under the hard constraints, the profile weights and the scoring "
            "assumptions in `docs/scoring.md`. It is not an absolute truth about which bus is best.",
            "- The profile weights are invented for this project, not measured from real travellers.",
            "- Price and duration are scored relative to the offers that passed the filter (`docs/scoring.md`, D15), "
            "so the scores only have meaning within this request.",
            "- Reproduce a single profile with `python main.py --destination Malaga --from 2026-07-12 --to "
            "2026-07-14 --budget 50 --max-transfers 1 --changeable --profile <name>`, or all at once with "
            "`--compare-profiles`.", ""]
    return "\n".join(out)


def main() -> None:
    target = Path(__file__).resolve().parent.parent / "docs" / "profile_comparison.md"
    target.write_text(build_report(), encoding="utf-8", newline="\n")
    print(f"wrote {target}")


if __name__ == "__main__":
    main()
